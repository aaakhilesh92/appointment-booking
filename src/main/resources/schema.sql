CREATE TABLE IF NOT EXISTS vfs_login_attempt (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL,
    successful BOOLEAN,
    insert_date TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    modified_date TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE vfs_login_attempt
    ADD COLUMN IF NOT EXISTS successful BOOLEAN;

ALTER TABLE vfs_login_attempt
    ADD COLUMN IF NOT EXISTS insert_date TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP;

ALTER TABLE vfs_login_attempt
    ADD COLUMN IF NOT EXISTS modified_date TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP;

CREATE INDEX IF NOT EXISTS idx_vfs_login_email
    ON vfs_login_attempt (email);

CREATE TABLE IF NOT EXISTS vfs_slot_alert (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL,
    alert_message TEXT NOT NULL,
    insert_date TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    modified_date TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_vfs_slot_alert_email
    ON vfs_slot_alert (email DESC);
